// Generates schema.json and docs/rules.md from src/rules.ts. Run with `npm run gen`.
import { writeFileSync } from "node:fs";
import { RULES, RULE_IDS } from "../src/rules.js";

const levels = ["error", "warning", "info", "off"];
const schema = {
  $schema: "http://json-schema.org/draft-07/schema#",
  title: "slotguard config",
  type: "object",
  additionalProperties: false,
  properties: {
    $schema: { type: "string" },
    include: { type: "array", items: { type: "string" }, description: "Globs (source path or source:Contract) to consider. Empty means all." },
    exclude: { type: "array", items: { type: "string" }, description: "Globs to skip. Replaces the default list." },
    extraExclude: { type: "array", items: { type: "string" }, description: "Globs to skip in addition to the defaults." },
    contracts: { type: "array", items: { type: "string" }, description: "Contracts always checked, by name, source path or source:Contract glob." },
    scope: { enum: ["upgradeable", "all"] },
    failOn: { enum: ["error", "warning", "info", "never"] },
    rules: {
      type: "object",
      additionalProperties: false,
      properties: Object.fromEntries(RULE_IDS.map((id) => [id, { enum: levels, description: RULES[id].description }])),
    },
  },
};
writeFileSync("schema.json", JSON.stringify(schema, null, 2) + "\n");

const sections = RULE_IDS.map((id) => `## ${id}\n\nDefault severity: **${RULES[id].severity}**\n\n${RULES[id].description}\n`);
const rows = RULE_IDS.map((id) => `| [\`${id}\`](#${id}) | ${RULES[id].severity} | ${RULES[id].description} |`);
writeFileSync(
  "docs/rules.md",
  `# Rules

<!-- Generated by \`npm run gen\` from src/rules.ts. -->

Every finding has a rule id and a severity. Override severities per rule in the config file:

\`\`\`json
{ "rules": { "storage-var-renamed": "error", "abi-function-mutability-changed": "off" } }
\`\`\`

| Rule | Default | Meaning |
| --- | --- | --- |
${rows.join("\n")}

${sections.join("\n")}`,
);
